#!/usr/bin/env node
/**
 * Builds a self-hosted subset of the Material Symbols Outlined icon font that
 * contains only the icons Inkframe uses (the full font is ~4 MB).
 *
 * Run after adding or renaming an icon:  npm run icons:build
 *
 * This is a development-time step: it downloads the subset once from the
 * Google Fonts API and writes it into the repository. The app itself never
 * contacts Google. The font is licensed under Apache 2.0.
 */
import { readdirSync, readFileSync, statSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, relative, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = join(root, 'projects/inkframe-editor/src/styles/fonts');
const SOURCE_DIRS = ['projects/inkframe-editor', 'src'];

/**
 * Icons chosen at runtime, which a source scan cannot see: computed in
 * expressions or passed in through inputs.
 */
const DYNAMIC_ICONS = [
  'light_mode', 'dark_mode', // toolbar theme toggle
  'format_align_left', 'format_align_center', 'format_align_right', // table alignment
  'description', // empty-state default
  'info', 'warning', 'check_circle', 'error', // callouts and toasts
];

/** Finds icon names in templates and extension definitions. */
export function collectIconNames(rootDir = root) {
  const names = new Set(DYNAMIC_ICONS);
  const patterns = [
    /<mat-icon[^>]*>\s*([a-z0-9_]+)\s*<\/mat-icon>/g, // <mat-icon>format_bold</mat-icon>
    /\bicon:\s*'([a-z0-9_]+)'/g, // extension items: icon: 'format_bold'
    /<mat-icon[^>]*>\s*\{\{[^}]*\}\}\s*<\/mat-icon>/g, // dynamic: names inside the expression
  ];
  const walk = (dir) => {
    for (const entry of readdirSync(dir)) {
      if (entry === 'node_modules' || entry === 'dist' || entry.startsWith('.')) continue;
      const path = join(dir, entry);
      if (statSync(path).isDirectory()) walk(path);
      else if (/\.(ts|html)$/.test(entry) && !entry.endsWith('.spec.ts')) {
        const text = readFileSync(path, 'utf8');
        for (const [i, re] of patterns.entries()) {
          for (const m of text.matchAll(re)) {
            if (i < 2) names.add(m[1]);
            else for (const q of m[0].matchAll(/'([a-z0-9_]+)'/g)) names.add(q[1]);
          }
        }
      }
    }
  };
  for (const dir of SOURCE_DIRS) walk(join(rootDir, dir));
  return [...names].sort(); // the API requires alphabetical order
}

async function main() {
  const names = collectIconNames();
  const UA =
    'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36';
  const cssUrl =
    'https://fonts.googleapis.com/css2?family=Material+Symbols+Outlined:opsz,wght,FILL,GRAD@24,400,0,0' +
    `&icon_names=${names.join(',')}&display=block`;

  const css = await (await fetch(cssUrl, { headers: { 'User-Agent': UA } })).text();
  const fontUrl = /src:\s*url\(([^)]+)\)\s*format\('woff2'\)/.exec(css)?.[1];
  if (!fontUrl) throw new Error(`Unexpected response from Google Fonts:\n${css.slice(0, 500)}`);
  const font = Buffer.from(await (await fetch(fontUrl, { headers: { 'User-Agent': UA } })).arrayBuffer());

  const classRule = css.slice(css.indexOf('.material-symbols-outlined')).trim();
  mkdirSync(outDir, { recursive: true });
  writeFileSync(join(outDir, 'material-symbols-outlined.woff2'), font);
  writeFileSync(join(outDir, 'icon-names.json'), JSON.stringify(names, null, 2) + '\n');
  writeFileSync(
    join(outDir, 'icons.css'),
    `/*
 * Material Symbols Outlined (Apache License 2.0), subset to the ${names.length} icons Inkframe uses.
 * Generated by scripts/build-icon-font.mjs. Do not edit; run \`npm run icons:build\` instead.
 */
@font-face {
  font-family: 'Material Symbols Outlined';
  font-style: normal;
  font-weight: 400;
  font-display: block;
  src: url('./material-symbols-outlined.woff2') format('woff2');
}

${classRule}
`,
  );
  console.log(
    `Wrote ${names.length} icons (${(font.length / 1024).toFixed(1)} kB) to ${relative(root, outDir)}`,
  );
}

/** `--check`: fail if the source uses an icon the committed subset lacks (used in CI). */
function check() {
  const subset = JSON.parse(readFileSync(join(outDir, 'icon-names.json'), 'utf8'));
  const missing = collectIconNames().filter((name) => !subset.includes(name));
  if (missing.length) {
    console.error(`Icons missing from the font subset: ${missing.join(', ')}\nRun: npm run icons:build`);
    process.exit(1);
  }
  console.log(`Icon font subset is up to date (${subset.length} icons).`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  if (process.argv.includes('--check')) {
    check();
  } else {
    main().catch((e) => {
      console.error(e);
      process.exit(1);
    });
  }
}
